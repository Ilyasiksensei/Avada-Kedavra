def rezhim_ozhidaniya(user_id, seconds):
    """Функция имитации печати и паузы"""
    bot.send_chat_action(user_id, 'typing')
    # Делим ожидание на короткие отрезки, чтобы можно было прервать
    for _ in range(seconds):
        if na_pauze.get(user_id): return False
        time.sleep(1)
    return True

def zapustit_scenu(user_id, scene_id):
    scene = SCENES.get(scene_id)
    if not scene: 
        print(f"Ошибка: Сцена {scene_id} не найдена")
        return
    
    nps_pannye[user_id]['scene'] = scene_id 

    # --- 1. ГОТОВИМ КНОПКИ ---
    markup = None
    if scene.get('type') == 'buttons':
        markup = types.ReplyKeyboardMarkup(resize_keyboard=True, one_time_keyboard=True)
        for btn in scene['buttons']:
            markup.add(types.KeyboardButton(btn))

    ubrat = types.ReplyKeyboardRemove()

    # Если мы ждем приветствия, ничего не отправляем
    if scene.get('type') == 'wait_hi':
        return
    
    # --- 2. ОТПРАВЛЯЕМ ТЕКСТ (ЕСЛИ ЕСТЬ) ---
    tekst_byl = False # Флаг, чтобы понять, был ли текст

    if 'text' in scene:
        tekst_byl = True
        messages = scene['text']
        count = len(messages)

        for i, msg in enumerate(messages):
            if not msg or not msg.strip(): continue
            
            if msg.strip() == "...":
                time.sleep(1.5)
                continue

            wait = max(2, len(msg) // 15)
            if not rezhim_ozhidaniya(user_id, wait): return
            
            # Прикрепляем кнопки только к последнему сообщению
            tekushaya_klava = None
            if i == 0: tekushaya_klava = ubrat
            if markup and i == count - 1: tekushaya_klava = markup
            
            try:
                bot.send_message(user_id, msg, reply_markup=tekushaya_klava)
            except Exception as e:
                print(f"Ошибка отправки: {e}")

    # --- 3. ЕСЛИ ТЕКСТА НЕ БЫЛО, НО ЕСТЬ КНОПКИ ---
    if not tekst_byl and markup:
        bot.send_message(user_id, "Выбери:", reply_markup=markup)

    # --- 4. ВИЗУАЛЬНОЕ ОЖИДАНИЕ ДЛЯ ЗАГАДОК ---
    if scene.get('type') in ['mood_check', 'wait_ready', 'riddle']:
        pass 

    # --- 5. 🔥 ИСПРАВЛЕННЫЙ АВТОПЕРЕХОД 🔥 ---
    # Переходим только если это НЕ кнопки И НЕ ожидание ввода от юзера
    if 'next_scene' in scene:
        # Список типов сцен, которые ТРЕБУЮТ остановки и ввода текста от юзера
        input_types = ['buttons', 'riddle', 'mood_check', 'wait_ready', 'wait_hi']
        
        if scene.get('type') not in input_types:
            time.sleep(1.5) 
            zapustit_scenu(user_id, scene['next_scene'])

