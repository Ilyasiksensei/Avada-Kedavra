@bot.message_handler(commands=['start'])
def start(message):
    user_id = message.chat.id
    na_pauze[user_id] = False
    # Сбрасываем прогресс в начало (Сцена 0)
    nps_pannye[user_id] = {'scene': 0, 'fail_count': 0}
    bot.send_message(user_id, "Привет", reply_markup=types.ReplyKeyboardRemove())

@bot.message_handler(func=lambda message: True)
def obrabotka_soobsheniy(message):
    user_id = message.chat.id
    
    # Инициализация профиля, если бот перезагружался
    if user_id not in nps_pannye:
        nps_pannye[user_id] = {'scene': 0, 'fail_count': 0}
        na_pauze[user_id] = False

    # Получаем текущие данные
    curr_id = nps_pannye.get(user_id, {}).get('scene', 0)
    scene = SCENES.get(curr_id)
    
    # Чистим текст от пробелов и делаем маленьким для проверок
    text_original = message.text.strip()
    text_lower = message.text.lower().strip()

    # -------------------------------------------------------------
    # 1. ПРИОРИТЕТ: ВЫХОД ИЗ ПАУЗЫ
    # -------------------------------------------------------------
    if na_pauze.get(user_id):
        if any(w in text_lower for w in ready_words):
            na_pauze[user_id] = False
            bot.send_message(user_id, "Возобновляем! ▶️")
            zapustit_scenu(user_id, curr_id) # Повторяем сцену
        return 

    # -------------------------------------------------------------
    # 2. ПРИОРИТЕТ: НАЖАТИЕ НА КНОПКУ (Сюжет)
    # -------------------------------------------------------------
    if scene and scene.get('type') == 'buttons':
        if text_original in scene['buttons']:
            next_id = scene['buttons'][text_original]
            zapustit_scenu(user_id, next_id)
            return
        else:
            # УБРАН ПАЛЕЦ 👇
            bot.send_message(user_id, "Пожалуйста, используй кнопки для выбора ответа.")
            return

    # -------------------------------------------------------------
    # 3. ПРИОРИТЕТ: КОМАНДЫ ПАУЗЫ
    # -------------------------------------------------------------
    if any(w in text_lower for w in control_words):
        na_pauze[user_id] = True
        bot.send_message(user_id, "🛑 Пауза. Напиши 'готово' или 'погнали', когда вернешься.")
        return

    # -------------------------------------------------------------
    # 4. ПРИОРИТЕТ: ОБРАБОТКА ВВОДА (Если это не кнопки)
    # -------------------------------------------------------------
    if not scene: 
        bot.send_message(user_id, "Ошибка: Сцена потеряна. Нажми /start")
        return

    scene_type = scene.get('type')

    # Приветствие
    if scene_type == 'wait_hi':
        if any(w in text_lower for w in hi):
            nps_pannye[user_id]['fail_count'] = 0
            zapustit_scenu(user_id, 1) 
        else:
            fails = nps_pannye[user_id].get('fail_count', 0) + 1
            nps_pannye[user_id]['fail_count'] = fails
            if fails == 1: bot.send_message(user_id, "Диль, Привет 🙂")
            elif fails == 2: bot.send_message(user_id, "ДИЛЬЬЬНАААЗ АУУУ ПРИИИВЕЕЕТ! 😆")
            else: bot.send_message(user_id, "Хм… жду приветствия 😏")

    # Настроение
    elif scene_type == 'mood_check':
        if any(w in text_lower for w in great):
            bot.send_message(user_id, "Ого, ты сияешь! 🌟 Продолжай в том же духе, мир готов к твоей энергии! 🔥")
            zapustit_scenu(user_id, scene['next_scene_good'])
        elif any(w in text_lower for w in good):
            bot.send_message(user_id, "Умничка! Рад за тебя! 😃")
            zapustit_scenu(user_id, scene['next_scene_good'])
        elif any(w in text_lower for w in bad):
            bot.send_message(user_id, f"Хм… {text_original.capitalize()}? 😠 Забудь про {text_original.capitalize()}! Ты сильнее, чем думаешь. Встань, вдохни и дай всем жару! 🔥 Только меня не прикончи 😊")
            zapustit_scenu(user_id, scene['next_scene_bad'])
        elif any(w in text_lower for w in sadness):
            bot.send_message(user_id, "Помни, солнышко, я всегда тебя любил, какой бы ты не была 💛")
            zapustit_scenu(user_id, scene['next_scene_bad'])
        else:
            bot.send_message(user_id, "Так я не понял тебя? 🤔")
        

# Сцена: Готовность (wait_ready)
    elif scene_type == 'wait_ready':
        if any(w in text_lower for w in ready_words):
            bot.send_message(user_id, "Отлично! 🚀")
            zapustit_scenu(user_id, scene['next_scene'])
        else:
            bot.send_message(user_id, "Напиши 'готово' или 'погнали'!")

    # Сцена: Загадка (riddle)
    elif scene_type == 'riddle':
        key = scene.get('riddle_key')
        
        # Проверяем правильный ответ
        if any(ans in text_lower for ans in riddles_list[key]['answer']):
            zapustit_scenu(user_id, scene['next_scene'])
        
        # Проверяем спам-слова
        elif 'spam_words' in scene and any(s in text_lower for s in scene['spam_words']):
            # Просто шлем текст, не перезапускаем сцену, чтобы не растить стек вызовов
            bot.send_message(user_id, "Ну же, назови имя... 🤨")
            return
        
        # Неверный ответ
        else:
            if 'fail_scene' in scene:
                zapustit_scenu(user_id, scene['fail_scene'])
            else:
                bot.send_message(user_id, "Неверно! Подумай еще 🧠")

    # Сцена: Автопереход (на случай сбоя)
    elif 'next_scene' in scene:
        zapustit_scenu(user_id, scene['next_scene'])
    
    # Если ничего не подошло
    else:
        bot.send_message(user_id, "Я тебя не понимаю. Следуй сюжету! 👇")

